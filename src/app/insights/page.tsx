"use client";

import { useEffect, useState } from "react";
import { moodStore, sleepStore, sleepDurationMinutes, symptomStore } from "@/lib/storage";

/**
 * Computed, non-AI insights.
 *
 * This page implements the "evidence-grounded" half of section 8 —
 * real descriptive statistics calculated from the user's own
 * records — but NOT the AI plain-language interpretation layer
 * (section 8.6), which requires a configured server-side AI
 * endpoint (AI_PROVIDER / AI_API_KEY) that is not wired up in this
 * starter. The numbers below are real; the prose around them is
 * template text, not model output, so nothing here is fabricated.
 */
export default function InsightsPage() {
  const [stats, setStats] = useState<{
    moodCount: number;
    avgMood?: number;
    avgMoodFirstHalf?: number;
    avgMoodSecondHalf?: number;
    sleepMoodNote?: string;
    topSymptoms: { name: string; count: number }[];
  }>({ moodCount: 0, topSymptoms: [] });

  useEffect(() => {
    const moods = moodStore.list().slice().reverse(); // oldest -> newest
    const moodCount = moods.length;
    const avgMood = moodCount ? round1(moods.reduce((s, m) => s + m.mood, 0) / moodCount) : undefined;

    let avgMoodFirstHalf: number | undefined;
    let avgMoodSecondHalf: number | undefined;
    if (moodCount >= 8) {
      const mid = Math.floor(moodCount / 2);
      avgMoodFirstHalf = round1(moods.slice(0, mid).reduce((s, m) => s + m.mood, 0) / mid);
      avgMoodSecondHalf = round1(moods.slice(mid).reduce((s, m) => s + m.mood, 0) / (moodCount - mid));
    }

    // Simple descriptive pairing of sleep duration the night before vs next-day mood.
    let sleepMoodNote: string | undefined;
    const sleeps = sleepStore.list();
    if (sleeps.length >= 5 && moodCount >= 5) {
      const pairs: { sleepMin: number; moodVal: number }[] = [];
      for (const s of sleeps) {
        const nextDayMood = moods.find((m) => m.date === s.date);
        if (nextDayMood) {
          pairs.push({ sleepMin: sleepDurationMinutes(s.bedtime, s.wakeTime), moodVal: nextDayMood.mood });
        }
      }
      if (pairs.length >= 5) {
        const shortSleep = pairs.filter((p) => p.sleepMin < 360);
        const longerSleep = pairs.filter((p) => p.sleepMin >= 360);
        if (shortSleep.length >= 2 && longerSleep.length >= 2) {
          const avgShort = round1(shortSleep.reduce((s, p) => s + p.moodVal, 0) / shortSleep.length);
          const avgLong = round1(longerSleep.reduce((s, p) => s + p.moodVal, 0) / longerSleep.length);
          sleepMoodNote = `On days after under 6 hours of sleep (${shortSleep.length} observations), average same-day mood was ${avgShort}/10, versus ${avgLong}/10 on days after 6+ hours (${longerSleep.length} observations). This is a descriptive comparison, not a controlled test — other factors could explain the difference.`;
        }
      }
    }

    const obs = symptomStore.list();
    const defs = symptomStore.definitions();
    const counts = new Map<string, number>();
    for (const o of obs) counts.set(o.symptomId, (counts.get(o.symptomId) ?? 0) + 1);
    const topSymptoms = Array.from(counts.entries())
      .sort((a, b) => b[1] - a[1])
      .slice(0, 5)
      .map(([id, count]) => ({ name: defs.find((d) => d.id === id)?.name ?? "Unknown", count }));

    setStats({ moodCount, avgMood, avgMoodFirstHalf, avgMoodSecondHalf, sleepMoodNote, topSymptoms });
  }, []);

  return (
    <div className="space-y-6">
      <h1 className="text-xl font-semibold">Insights</h1>
      <p className="text-sm text-text-secondary">
        These are computed directly from your records — not generated by AI yet. Connect an AI provider in
        Settings to add plain-language interpretation on top of these numbers.
      </p>

      {stats.moodCount === 0 && (
        <div className="card text-sm text-text-secondary">Log a few mood check-ins to see patterns here.</div>
      )}

      {stats.moodCount > 0 && (
        <div className="card space-y-2">
          <p className="text-sm font-medium">Mood overview</p>
          <p className="text-sm">
            Based on {stats.moodCount} mood entries, your average mood is {stats.avgMood}/10.
          </p>
          {stats.avgMoodFirstHalf !== undefined && (
            <p className="text-sm">
              Earlier entries averaged {stats.avgMoodFirstHalf}/10, compared to {stats.avgMoodSecondHalf}/10 more
              recently.
            </p>
          )}
        </div>
      )}

      {stats.sleepMoodNote && (
        <div className="card">
          <p className="text-sm font-medium mb-1">Sleep and mood</p>
          <p className="text-sm">{stats.sleepMoodNote}</p>
        </div>
      )}

      {stats.topSymptoms.length > 0 && (
        <div className="card">
          <p className="text-sm font-medium mb-2">Most logged symptoms</p>
          <ul className="text-sm space-y-1">
            {stats.topSymptoms.map((s) => (
              <li key={s.name} className="flex justify-between">
                <span>{s.name}</span>
                <span className="text-text-secondary">{s.count}x</span>
              </li>
            ))}
          </ul>
        </div>
      )}

      <p className="text-xs text-text-secondary">
        K? does not diagnose conditions or claim that any tracked factor causes another. These are observational
        summaries meant to support conversations with your psychiatrist, not replace them.
      </p>
    </div>
  );
}

function round1(n: number) {
  return Math.round(n * 10) / 10;
}
